import { randomUUID } from 'node:crypto';
import { expect, test } from '@playwright/test';

test('keeps theme, navigation, project drafts and history usable at 360 px', async ({ page }) => {
  await page.setViewportSize({ width: 360, height: 800 });
  await page.goto('/');
  await expect(page.getByRole('combobox', { name: 'Tema' })).toHaveValue('dark');
  await page.getByRole('combobox', { name: 'Tema' }).selectOption('light');
  await page.reload();
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light');

  await page.goto('/register');
  await page.getByLabel('Nombre', { exact: true }).fill('Prueba de usabilidad');
  await page.getByLabel('Correo electrónico').fill(`usability-${randomUUID()}@example.test`);
  await page.getByLabel('Contraseña', { exact: true }).fill('Usability-test-password-2026!');
  await page.getByLabel('Confirma tu contraseña').fill('Usability-test-password-2026!');
  await page.getByRole('button', { name: 'Crear cuenta' }).click();

  const navigation = page.getByRole('navigation', { name: 'Navegación privada' });
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light');
  await page.getByRole('link', { name: 'Crear mi primer proyecto' }).click();
  await page.getByLabel('Nombre del proyecto').fill('Proyecto móvil');
  await page.getByRole('button', { name: 'Crear cliente' }).click();
  await page.getByRole('dialog', { name: 'Nuevo cliente' }).getByLabel('Nombre del cliente').fill('Cliente móvil');
  await page.getByRole('button', { name: 'Guardar cliente' }).click();
  await expect(page.getByRole('dialog', { name: 'Nuevo cliente' })).toBeHidden();
  await expect(page.getByLabel('Nombre del proyecto')).toHaveValue('Proyecto móvil');
  await page.getByLabel('Origen del proyecto').fill('Directo');
  await page.getByLabel('Monto acordado (MXN)').fill('100');
  await page.getByLabel('Pagos acordados').fill('3');
  await expect(page.getByLabel('Monto acordado (MXN)')).toHaveValue('100');
  await expect(page.getByLabel('Pagos acordados')).toHaveValue('3');
  await expect(page.getByText('MXN 33.33')).toBeVisible();
  await page.getByRole('button', { name: 'Guardar proyecto' }).click();
  await page.getByRole('link', { name: 'Editar proyecto' }).click();
  await page.getByLabel('Nombre del proyecto').fill('Proyecto corregido');
  await page.getByRole('link', { name: 'Cancelar' }).click();
  await page.getByRole('button', { name: 'Seguir editando' }).click();
  await expect(page.getByLabel('Nombre del proyecto')).toHaveValue('Proyecto corregido');
  await page.getByRole('button', { name: 'Guardar cambios' }).click();
  await expect(page.getByRole('heading', { name: 'Proyecto corregido' })).toBeVisible();

  await page.goto('/projects/new');
  await page.getByRole('combobox', { name: 'Cliente' }).selectOption({ label: 'Cliente móvil' });
  await page.getByLabel('Nombre del proyecto').fill('Segundo proyecto');
  await page.getByLabel('Origen del proyecto').fill('Directo');
  await page.getByLabel('Monto acordado (MXN)').fill('50');
  await page.getByLabel('Pagos acordados').fill('2');
  await page.getByRole('button', { name: 'Guardar proyecto' }).click();
  await expect(page.getByRole('heading', { name: 'Segundo proyecto' })).toBeVisible();

  await navigation.getByRole('link', { name: 'Cobros' }).click();
  await expect(navigation.getByRole('link', { name: 'Cobros' })).toHaveAttribute('aria-current', 'page');
  await page.getByRole('link', { name: 'Registrar cobro' }).click();
  const projectSelector = page.getByRole('combobox', { name: 'Proyecto', exact: true });
  await projectSelector.selectOption({ label: 'Segundo proyecto · Cliente móvil' });
  await page.getByLabel('Fecha de pago').fill('2025-11-13');
  await page.getByLabel('Importe (MXN)').fill('30');
  await expect(page.getByText('Saldo tras guardar: MXN 20.00')).toBeVisible();
  await projectSelector.selectOption({ label: 'Proyecto corregido · Cliente móvil' });
  await expect(page.getByLabel('Fecha de pago')).toHaveValue('2025-11-13');
  await expect(page.getByLabel('Importe (MXN)')).toHaveValue('30');
  await expect(page.getByText('Saldo tras guardar: MXN 70.00')).toBeVisible();
  await page.getByRole('button', { name: 'Guardar cobro' }).click();
  await page.getByRole('link', { name: 'Ver detalle del cobro' }).click();
  await page.getByRole('button', { name: 'Editar cobro' }).click();
  await page.getByLabel('Importe abonado (MXN)').fill('21');
  await expect(page.getByText('Saldo tras guardar: MXN 79.00')).toBeVisible();
  await page.getByRole('button', { name: 'Guardar cambios' }).click();
  await expect(page.getByRole('form', { name: 'Editar cobro' })).toBeHidden();

  await navigation.getByRole('link', { name: 'Cobros' }).click();
  await expect(page.getByRole('heading', { name: 'Cobros guardados' })).toBeVisible();
  await page.getByRole('button', { name: /noviembre 2025/i }).click();
  await expect(page.getByText('MXN 21.00').first()).toBeVisible();
  const monthTrigger = page.getByRole('button', { name: 'Elegir mes' });
  await monthTrigger.click();
  const monthDialog = page.getByRole('dialog', { name: 'Mes del reporte' });
  await monthDialog.getByRole('spinbutton', { name: 'Año' }).fill('2000');
  await monthDialog.getByRole('button', { name: 'Enero 2000' }).click();
  await page.keyboard.press('Escape');
  await expect(monthTrigger).toBeFocused();
  await expect(page.getByText('MXN 21.00').first()).toBeVisible();
  await monthTrigger.click();
  await monthDialog.getByRole('spinbutton', { name: 'Año' }).fill('2000');
  await monthDialog.getByRole('button', { name: 'Enero 2000' }).click();
  await monthDialog.getByRole('button', { name: 'Aplicar' }).click();
  await expect(page.getByText('No hay cobros en este mes.', { exact: false })).toBeVisible();
  await navigation.getByRole('link', { name: 'Proyectos' }).click();
  await expect(page.getByRole('link', { name: 'Proyecto corregido' })).toBeVisible();
  await expect(page.getByText('Cliente móvil', { exact: true })).toHaveCount(2);
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(360);
  await page.setViewportSize({ width: 1080, height: 800 });
  await page.getByRole('combobox', { name: 'Tema' }).selectOption('dark');
  await navigation.getByRole('link', { name: 'Tablero' }).click();
  await expect(page.getByRole('heading', { name: 'Tablero' })).toBeVisible();
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark');
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(1080);
});
